// Get translation for key
function t(key, lang) {
    if (!lang) lang = 'en';
    var dict = translations[lang] || translations['en'];
    return dict[key] || key;
}

// Replace {placeholder} in template string
function formatTemplate(template, data) {
    var result = template;
    for (var key in data) {
        result = result.replace('{' + key + '}', data[key]);
    }
    return result;
}