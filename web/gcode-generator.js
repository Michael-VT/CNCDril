// G-Code Generator for CNC Drill Files

class GCodeGenerator {
    constructor(params = null) {
        this.params = params || {
            safeZ: 5.0,
            drillZ: -2.0,
            feedRate: 100,
            plungeRate: 50,
            toolChangeX: 0.0,
            toolChangeY: 0.0,
        };
    }
    
    /**
     * Generate G-Code from tools and holes
     */
    generate(tools, holes, optimizedHoles) {
        const lines = [];
        
        // Header
        lines.push('% CNCDril G-Code Output');
        lines.push('% Generated by CNCDril Web Version');
        lines.push('G21 ; Set units to mm');
        lines.push('G90 ; Absolute positioning');
        lines.push(`G0 Z${this.params.safeZ.toFixed(3)} ; Move to safe height`);
        lines.push('');
        
        // Process each tool
        const sortedToolIds = Object.keys(holes).sort();
        
        for (const toolId of sortedToolIds) {
            const tool = tools[toolId];
            const points = optimizedHoles[toolId] || [];
            
            if (!tool || points.length === 0) continue;
            
            lines.push(`% Tool ${toolId} - Ø${tool.diameter.toFixed(2)}mm - ${points.length} holes`);
            
            // Move to tool change position
            lines.push(`G0 X${this.params.toolChangeX.toFixed(3)} Y${this.params.toolChangeY.toFixed(3)}`);
            lines.push(`T${parseInt(toolId)} M6 ; Tool change`);
            lines.push('S1000 M3 ; Spindle on');
            lines.push('');
            
            // Drill holes
            for (let i = 0; i < points.length; i++) {
                const point = points[i];
                lines.push(`% Hole ${i + 1}`);
                lines.push(`G0 X${point.x.toFixed(3)} Y${point.y.toFixed(3)} ; Move to hole`);
                lines.push(`G1 Z${this.params.drillZ.toFixed(3)} F${this.params.plungeRate} ; Drill`);
                lines.push(`G0 Z${this.params.safeZ.toFixed(3)} ; Retract`);
                lines.push('');
            }
        }
        
        // Footer
        lines.push('M5 ; Spindle off');
        lines.push('G0 X0 Y0 ; Move to origin');
        lines.push('M30 ; End of program');
        
        return lines.join('\n');
    }
    
    /**
     * Get statistics about the G-Code
     */
    getStats(tools, holes, optimizedHoles) {
        const stats = {
            totalTools: Object.keys(tools).length,
            totalHoles: 0,
            totalDistance: 0,
            estimatedTime: 0,
        };
        
        const sortedToolIds = Object.keys(holes).sort();
        
        for (const toolId of sortedToolIds) {
            const points = optimizedHoles[toolId] || [];
            stats.totalHoles += points.length;
            
            if (points.length > 0) {
                const pathLength = OptimizationAlgorithms.calculatePathLength(points);
                stats.totalDistance += pathLength;
                
                // Estimate time (rough approximation)
                const timePerHole = (Math.abs(this.params.drillZ) / this.params.plungeRate * 60) + 
                                   (Math.abs(this.params.drillZ) / this.params.feedRate * 60) + 2; // +2s for positioning
                stats.estimatedTime += points.length * timePerHole;
            }
        }
        
        return stats;
    }
}

// Export for use in other modules
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { GCodeGenerator };
}